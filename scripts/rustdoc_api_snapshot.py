#!/usr/bin/env python3
"""Build a compact public API snapshot from rustdoc JSON.

Run `cargo +nightly rustdoc -p kapitsa --all-features -- -Z unstable-options --output-format json`
first. The generated text lists reachable public paths and is intended to be
committed as `docs/public-api-rustdoc.txt`.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "target" / "doc" / "kapitsa.json"
OUTPUT = ROOT / "docs" / "public-api-rustdoc.txt"


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows: set[str] = set()
    for item in data.get("paths", {}).values():
        if item.get("crate_id") != 0:
            continue
        path = "::".join(item.get("path", []))
        kind = item.get("kind", "item")
        if path:
            rows.add(f"{kind} {path}")
    lines = [
        "# Kapitsa public API (rustdoc JSON)",
        "# Generated by scripts/rustdoc_api_snapshot.py; do not edit manually.",
        f"# crate={data.get('crate_version')} format={data.get('format_version')}",
        "",
        *sorted(rows),
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} public paths)")


if __name__ == "__main__":
    main()