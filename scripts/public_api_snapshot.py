#!/usr/bin/env python3
"""Generate a textual snapshot of the public `kapitsa` facade.

The snapshot lists public modules and root re-exports so API changes show up
as an explicit diff during review. It is intentionally source-derived: running
it after editing `crates/kapitsa/src/lib.rs` updates the snapshot.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "crates" / "kapitsa" / "src" / "lib.rs"
OUTPUT = ROOT / "docs" / "public-api.txt"


def strip_comments(line: str) -> str:
    return re.sub(r"//.*$", "", line).strip()


def collect_statements(text: str, prefix: str) -> list[str]:
    statements: list[str] = []
    buffer = ""
    for raw in text.splitlines():
        line = strip_comments(raw)
        if not line:
            continue
        if buffer:
            buffer += " " + line
        elif line.startswith(prefix):
            buffer = line
        else:
            continue
        if buffer.endswith(";"):
            statements.append(buffer)
            buffer = ""
    return statements


def names_from_use(statement: str) -> list[str]:
    body = statement[len("pub use ") :].rstrip(";").strip()
    if "{" not in body:
        item = body.split("::")[-1].strip()
        return [item] if item and item != "*" else []
    inner = body[body.index("{") + 1 : body.rindex("}")]
    names: list[str] = []
    for entry in inner.split(","):
        entry = entry.strip()
        if not entry:
            continue
        name = entry.split(" as ")[-1].strip() if " as " in entry else entry.split("::")[-1].strip()
        if name and name != "*":
            names.append(name)
    return names


def main() -> None:
    text = LIB.read_text(encoding="utf-8")
    modules = sorted(
        match.group(1)
        for match in re.finditer(r"^pub mod ([A-Za-z0-9_]+) \{", text, flags=re.MULTILINE)
    )
    root_uses = collect_statements(text, "pub use ")
    root_names: set[str] = set()
    for statement in root_uses:
        root_names.update(names_from_use(statement))

    lines = [
        "# Kapitsa public API snapshot",
        "# Generated by scripts/public_api_snapshot.py; do not edit manually.",
        "",
        "[modules]",
        *modules,
        "",
        "[root re-exports]",
        *sorted(root_names),
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(modules)} modules, {len(root_names)} root items)")


if __name__ == "__main__":
    main()