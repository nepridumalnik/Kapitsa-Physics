/// Benchmark-only timings and workload counts from the most recent world step.
#[cfg(feature = "bench-internals")]
#[doc(hidden)]
#[derive(Clone, Copy, Debug, Default)]
pub struct CollisionStepMetrics {
    /// Time spent building proxies and synchronizing the spatial index.
    pub spatial_index: Duration,
    /// Time spent generating broadphase candidate pairs.
    pub broad_phase: Duration,
    /// Time spent finding continuous collision impacts.
    pub ccd: Duration,
    /// Time spent on discrete narrowphase contact generation.
    pub narrow_phase: Duration,
    /// Time spent assigning contacts to deterministic islands.
    pub island_build: Duration,
    /// Time spent preparing and solving contact constraints.
    pub solver: Duration,
    /// Time spent constructing collision lifecycle events.
    pub events: Duration,
    /// Time spent committing body states and staged collision data.
    pub commit: Duration,
    /// Number of broadphase candidate collider pairs.
    pub candidate_count: usize,
    /// Number of contact points generated by the narrowphase.
    pub contact_count: usize,
    /// Number of continuous time-of-impact contacts resolved.
    pub ccd_impact_count: usize,
    /// Number of solver islands built for the step.
    pub island_count: usize,
    /// Approximate retained capacity of collision scratch buffers.
    pub retained_scratch_bytes: usize,
    /// Highest sampled retained scratch capacity during the last step.
    pub peak_scratch_bytes: usize,
    /// Approximate retained capacity of the committed spatial query index.
    pub committed_query_index_bytes: usize,
    /// Net increase in retained buffer capacity during this step, in bytes.
    pub logical_capacity_growth_bytes: usize,
    /// Logical copies of solver bodies created for island-local state.
    pub solver_body_copies: usize,
    /// Logical solver-manifold value copies across build and write-back.
    pub solver_manifold_copies: usize,
}

#[cfg(feature = "bench-internals")]
impl CollisionStepMetrics {
    /// Empty timing and workload snapshot.
    pub const ZERO: Self = Self {
        spatial_index: Duration::ZERO,
        broad_phase: Duration::ZERO,
        ccd: Duration::ZERO,
        narrow_phase: Duration::ZERO,
        island_build: Duration::ZERO,
        solver: Duration::ZERO,
        events: Duration::ZERO,
        commit: Duration::ZERO,
        candidate_count: 0,
        contact_count: 0,
        ccd_impact_count: 0,
        island_count: 0,
        retained_scratch_bytes: 0,
        peak_scratch_bytes: 0,
        committed_query_index_bytes: 0,
        logical_capacity_growth_bytes: 0,
        solver_body_copies: 0,
        solver_manifold_copies: 0,
    };
}
