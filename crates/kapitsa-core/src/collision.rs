/// Benchmark-only timings and workload counts from the most recent world step.
#[cfg(feature = "bench-internals")]
#[doc(hidden)]
#[derive(Clone, Copy, Debug, Default)]
pub struct CollisionStepMetrics {
    /// Time spent building proxies and synchronizing the spatial index.
    pub spatial_index: Duration,
    /// Time spent generating broadphase candidate pairs.
    pub broad_phase: Duration,
    /// Time spent finding continuous collision impacts.
    pub ccd: Duration,
    /// Time spent scanning the active broadphase candidates for the next TOI.
    pub ccd_toi_search: Duration,
    /// Time spent rebuilding the CCD broadphase after an impact.
    pub ccd_candidate_refresh: Duration,
    /// Time spent constructing and solving CCD contacts.
    pub ccd_contact_resolution: Duration,
    /// Time spent building CCD islands and preparing their initial TOIs.
    pub ccd_island_prepare: Duration,
    /// Time spent processing CCD islands, including local resweeps.
    pub ccd_island_execute: Duration,
    /// Time spent publishing CCD impacts into staged step results.
    pub ccd_island_commit: Duration,
    /// Time spent on discrete narrowphase contact generation.
    pub narrow_phase: Duration,
    /// Time spent assigning contacts to deterministic islands.
    pub island_build: Duration,
    /// Time spent materializing enabled joint constraints for the solver.
    pub joint_constraint_prepare: Duration,
    /// Time spent preparing and solving contact constraints.
    pub solver: Duration,
    /// Time spent grouping bodies and manifolds into solver islands.
    pub solver_prepare: Duration,
    /// Time spent running contact solver iterations after island preparation.
    pub solver_iterations: Duration,
    /// Time spent writing solved states and manifolds back to staged data.
    pub solver_writeback: Duration,
    /// Time spent constructing collision lifecycle events.
    pub events: Duration,
    /// Time spent committing body states and staged collision data.
    pub commit: Duration,
    /// Number of broadphase candidate collider pairs.
    pub candidate_count: usize,
    /// Number of contact points generated by the narrowphase.
    pub contact_count: usize,
    /// Number of continuous time-of-impact contacts resolved.
    pub ccd_impact_count: usize,
    /// Number of unresolved CCD contacts handled by local budget clipping.
    pub ccd_clipped_island_count: usize,
    /// Distinct dynamic bodies stopped after reaching the impact budget.
    pub ccd_clipped_body_count: usize,
    /// Candidate pairs present when CCD processing began.
    pub ccd_initial_candidate_count: usize,
    /// Number of TOI evaluations performed by the CCD solver.
    pub ccd_toi_call_count: usize,
    /// TOI evaluations for pairs already evaluated earlier in this step.
    pub ccd_repeated_toi_call_count: usize,
    /// Number of broadphase candidate builds during this step.
    pub ccd_broad_phase_build_count: usize,
    /// Number of full CCD candidate refreshes after impacts.
    pub ccd_candidate_refresh_count: usize,
    /// Number of changed-body selective resweeps.
    pub ccd_resweep_count: usize,
    /// Body and unbounded collider proxies visited during selective resweeps.
    pub ccd_resweep_colliders_visited: usize,
    /// Number of changed-body collider proxies sent through spatial-index update.
    pub ccd_resweep_proxies_updated: usize,
    /// Resweep calls that found no dependency on another CCD island.
    pub ccd_local_resweep_count: usize,
    /// Resweep calls that discovered a dynamic dependency on another island.
    pub ccd_interisland_resweep_count: usize,
    /// Candidate TOIs recalculated by selective local resweeps.
    pub ccd_local_toi_recalculation_count: usize,
    /// Candidate TOIs invalidated by full-scene CCD replay.
    pub ccd_global_toi_recalculation_count: usize,
    /// Local replays of connected CCD island components.
    pub ccd_local_replay_count: usize,
    /// Number of CCD islands reprocessed by local or global replay.
    pub ccd_replayed_island_count: usize,
    /// Worker tasks launched by collision preparation or solving.
    pub worker_tasks_started: usize,
    /// Independent CCD islands evaluated through the parallel impact path.
    pub ccd_parallel_island_count: usize,
    /// Number of new pairs found during selective resweeps.
    pub ccd_new_candidate_count: usize,
    /// Number of full sequential restarts after a cross-island dependency.
    pub ccd_global_fallback_count: usize,
    /// Number of TOI entries invalidated by changed bodies.
    pub ccd_invalidated_toi_count: usize,
    /// Number of broadphase pairs after CCD resweeps complete.
    pub ccd_final_candidate_count: usize,
    /// Number of solver islands built for the step.
    pub island_count: usize,
    /// Number of independent CCD islands built for the step.
    pub ccd_island_count: usize,
    /// Largest solver island body count for the step.
    pub largest_island_body_count: usize,
    /// Largest solver island joint count for the step.
    pub largest_island_joint_count: usize,
    /// Largest solver island contact-manifold count for the step.
    pub largest_island_contact_count: usize,
    /// Approximate retained capacity of collision scratch buffers.
    pub retained_scratch_bytes: usize,
    /// Highest sampled retained scratch capacity during the last step.
    pub peak_scratch_bytes: usize,
    /// Approximate retained capacity of the committed spatial query index.
    pub committed_query_index_bytes: usize,
    /// Net increase in retained buffer capacity during this step, in bytes.
    pub logical_capacity_growth_bytes: usize,
    /// Logical copies of solver bodies created for island-local state.
    pub solver_body_copies: usize,
    /// Logical solver-manifold value copies across build and write-back.
    pub solver_manifold_copies: usize,
}

